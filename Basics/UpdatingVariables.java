public class UpdatingVariables {
    public static void main(String[] args) {
        int x = 5;
        System.out.println(x);
        x = 7;
        System.out.println(x);
        x += 6; //x = x+6
        System.out.println(x);
        x = x-20; //x -= 20
        System.out.println(x);
        x *= -5;
        System.out.println(x);
        x /= 7;
        System.out.println(x);
    }
}
