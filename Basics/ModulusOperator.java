public class ModulusOperator {
    public static void main(String[] args) {
    int a=8, b=2;

    System.out.println(a%b);
    System.out.println(3%4);
    System.out.println(12%12);
    System.out.println(37%10);
    System.out.println(37%-10);
    System.out.println(-37%10);
    System.out.println(-37%-10);

    }
}
